"""Writes app/src/analysis/engine/sheetsage2Vocab.ts: SheetSage2's token layout (the authors'
SheetSage2Tokenizer, schema v1, 300 s windows at 100 time steps per second), the prompt prefix the
app uses (timestamps and full chords), and for each of its 316 chord labels the app's chord index
it folds onto (root * 14 + quality, 168 = N; common.reduce_label, as for Tsumugi) and its bass.

    python gen_sheetsage2_vocab.py <SheetSage2 snapshot>
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import torch
from transformers import AutoConfig

from common import chord_index, reduce_label

OUT = Path(__file__).resolve().parents[4] / "app" / "src" / "analysis" / "engine" / "sheetsage2Vocab.ts"


def main() -> None:
    snap = sys.argv[1]
    cfg = AutoConfig.from_pretrained(snap, trust_remote_code=True)
    from importlib import import_module

    pkg = type(cfg).__module__.rsplit(".", 1)[0]
    Tok = import_module(pkg + ".tokenization_sheetsage2").SheetSage2Tokenizer
    tok = Tok(cfg.input_audio_length, cfg.time_hz, cfg.tokenizer_schema_version, expected_fingerprint=cfg.tokenizer_fingerprint)
    prompts = tok.normalize_prompts(("timestamp", "chord_full"))
    prefix = tok.prompt_prefix(prompts)
    if prefix[-1] == tok.eos_token:
        prefix = prefix[:-1]
    layout = {
        "nTokens": tok.n_tokens,
        "timeHz": tok.time_hz,
        "pad": tok.pad_token,
        "sos": tok.sos_token,
        "eos": tok.eos_token,
        "out": tok.out_token,
        "prefix": prefix,
        "shift": [tok.subbeat_shift_token_start, tok.subbeat_shift_token_end],
        "time": [tok.time_token_start, tok.time_token_end],
        "meter": [tok.meter_token_start, tok.meter_token_end],
        "eighth": [tok.eighth_position_token_start, tok.eighth_position_token_end],
        "structure": [tok.structure_token_start, tok.structure_token_end],
        "key": [tok.key_token_start, tok.key_token_end],
        "majmin": [tok.majmin_chord_token_start, tok.majmin_chord_token_end],
        "chord": [tok.full_chord_token_start, tok.full_chord_token_end],
        "pitch": [tok.pitch_token_start, tok.pitch_token_end],
        "duration": [tok.duration_token_start, tok.duration_token_end],
    }
    assert tok.n_tokens == tok.duration_token_end, "appended token blocks are not handled"
    labels = list(tok.full_chord_labels)
    idx, bass = [], []
    for l in labels:
        root, q, b = reduce_label(l)
        idx.append(chord_index(root, q))
        bass.append(-1 if root < 0 else (b - root) % 12)
    lines = [
        "// Generated by web/spikes/accords/modeles/gen_sheetsage2_vocab.py: do not edit.",
        "// SheetSage2's token layout (the authors' SheetSage2Tokenizer, schema v1, fingerprint",
        f"// {tok.vocab_fingerprint}), the prompt prefix « timestamps and full chords », and for each of its",
        f"// {len(labels)} chord labels (Harte) the app's chord index it folds onto (root * 14 + quality,",
        "// 168 = N) and its bass in semitones above the root (-1 for N).",
        "",
        f"export const SS2_LAYOUT = {json.dumps(layout)} as const;",
        "",
        f"export const SS2_LABELS: readonly string[] = {json.dumps(labels)};",
        "",
        f"export const SS2_TO_APP: readonly number[] = {json.dumps(idx)};",
        "",
        f"export const SS2_BASS: readonly number[] = {json.dumps(bass)};",
        "",
    ]
    OUT.write_text("\n".join(lines).replace('", "', '",\n  "'))
    print(f"{OUT}: {len(labels)} chord labels, {tok.n_tokens} tokens")


if __name__ == "__main__":
    main()
