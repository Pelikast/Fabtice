"""Writes app/src/analysis/engine/tsumugiVocab.ts: for each of Tsumugi-Chords' 745 chord
classes, its Harte label (the author's chord_to_mir_eval) and the app's chord index
(root * 14 + quality, 168 = N) it folds onto, exactly as the bench folded it
(common.reduce_label, combine.to_app_vocab).

    python gen_tsumugi_vocab.py
"""

from __future__ import annotations

from pathlib import Path

from common import chord_index, reduce_label
from run_tsumugi import detail_labels, ensure_src

OUT = Path(__file__).resolve().parents[4] / "app" / "src" / "analysis" / "engine" / "tsumugiVocab.ts"


def main() -> None:
    ensure_src()
    labels = detail_labels()
    idx = [chord_index(*reduce_label(l)[:2]) for l in labels]
    lines = [
        "// Generated by web/spikes/accords/modeles/gen_tsumugi_vocab.py: do not edit.",
        "// Tsumugi-Chords' 745 chord classes (index 12 * quality + root, « no chord » last):",
        "// their Harte label (the author's tsumugi_chords.theory.chord_to_mir_eval, MIT) and the",
        "// app's chord index each one folds onto (root * 14 + quality, 168 = N; extensions dropped),",
        "// as the bench measured it (variant `modele-a`).",
        "",
        f"export const TSUMUGI_LABELS: readonly string[] = {labels!r};".replace("'", "'"),
        "",
        f"export const TSUMUGI_TO_APP: readonly number[] = {idx!r};",
        "",
    ]
    # JSON-like arrays are valid TypeScript; wrap long lines loosely.
    text = "\n".join(lines).replace("', '", "',\n  '")
    OUT.write_text(text)
    print(f"{OUT}: {len(labels)} classes")


if __name__ == "__main__":
    main()
