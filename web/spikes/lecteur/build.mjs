// Bundles the AudioWorklet (src/processor.js and what it imports) into worklet/player-worklet.js.
// The site has no build step, so the bundle is committed.
//   npm i esbuild            (anywhere)
//   ESBUILD=/path/to/node_modules/esbuild/lib/main.js node build.mjs
const esbuild = await import(process.env.ESBUILD || 'esbuild');
await esbuild.build({
	entryPoints: ['src/processor.js'],
	bundle: true,
	format: 'iife',
	target: 'es2020',
	outfile: 'worklet/player-worklet.js',
	legalComments: 'inline',
	banner: { js: '/* Fabtice player worklet - generated by build.mjs from src/. SoundTouch JS: MPL-2.0 (see src/vendor/soundtouch/LICENSE). */' },
});
console.log('worklet/player-worklet.js written');
