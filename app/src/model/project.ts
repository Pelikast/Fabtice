// Data model of an open piece. Everything here is plain, serialisable data:
// no audio samples (they live in the audio registry and the engine) and no
// playhead position (read from the engine every animation frame).

import type { Instrument } from './harmony';
import type { TempoMap } from './tempoMap';

/** Seconds in source time: a position in the original recording, before any tempo change. */
export type Seconds = number;

/** A span of source time, `start` inclusive, `end` exclusive, `start < end`. */
export interface TimeRange {
  start: Seconds;
  end: Seconds;
}

/** Where the piece came from. */
export type ProjectSource =
  /** An audio file chosen or dropped by the user. */
  | { kind: 'file'; fileName: string }
  /** A link imported by the Mac app (yt-dlp, on the user's machine). */
  | { kind: 'link'; url: string; channel: string | null }
  /** The synthetic piece generated by `?demo`. */
  | { kind: 'demo' };

export type SourceKind = ProjectSource['kind'];

export interface Project {
  /** Random identifier, stable for the life of the project. */
  id: string;
  /** Title shown in the top bar (file name without extension, or the video title). */
  title: string;
  source: ProjectSource;
  /** Length of the longest track, in seconds. */
  duration: Seconds;
  /** Sample rate of the decoded tracks; always the engine rate (48 kHz). */
  sampleRate: number;
  /** ISO date of creation. */
  createdAt: string;
}

/**
 * Colour role of a track: picks its hue among the DESIGN.md track tokens.
 * `morceau` is the whole piece before any separation.
 */
export type TrackRole = 'morceau' | 'voix' | 'batterie' | 'basse' | 'guitare' | 'piano' | 'vents' | 'autres';

/** Reference to the decoded audio of a track (the samples are kept out of the store). */
export interface AudioRef {
  /** Key in the audio registry (`audio/registry.ts`) and, later, in project storage. */
  id: string;
  /** What produced it: the imported original, or a separation model (lot 3). */
  origin: 'original' | 'separated';
  channels: number;
  sampleRate: number;
  frames: number;
}

export interface Track {
  id: string;
  /** Display name, in French (« Morceau », « Basse »…). */
  name: string;
  role: TrackRole;
  mute: boolean;
  solo: boolean;
  /** Linear gain, 0…1. */
  volume: number;
  audio: AudioRef;
}

/** Loop of the transport. The region survives when the loop is switched off. */
export interface LoopState {
  region: TimeRange | null;
  enabled: boolean;
}

/** Live playback settings (applied by the light engine; « Appliquer » comes in lot 3). */
export interface PlaybackSettings {
  /** Transposition in semitones, −12…+12. */
  semitones: number;
  /** Fine tuning in cents, −50…+50, added to the semitones. */
  cents: number;
  /**
   * Playback speed as a ratio of the original tempo (1 = original, 0.5 = half
   * speed). The target BPM shown in the transport is derived from it and the
   * tempo map, see `targetBpm()` in `store/derived.ts`.
   */
  tempoRatio: number;
  /** Metronome on/off; it follows the tempo map. */
  metronome: boolean;
}

/** Sub-grid step: lines per beat before triplets (quarter, eighth, sixteenth, thirty-second notes). */
export type Subdivision = 1 | 2 | 4 | 8;

export type ViewMode = 'pistes' | 'grille';

export interface ViewSettings {
  mode: ViewMode;
  /** Horizontal scale of the Pistes view, in pixels per second of source time. */
  pxPerSecond: number;
  /** Height of one track lane, in CSS pixels. */
  trackHeight: number;
  /** « Auto »: the timeline fits the whole piece and all tracks in the window. */
  auto: boolean;
  subdivision: Subdivision;
  /** « Triolets »: 1.5 times more sub-grid lines per beat. */
  triplets: boolean;
  /** Magnet: seeking snaps to the active sub-grid. */
  snap: boolean;
  /** Scroll to keep the playhead in sight while playing. */
  follow: boolean;
  /** « Grille d'accords » written for a concert-pitch, B♭ or E♭ instrument (display only). */
  instrument: Instrument;
}

/** Notation of minor chords: « Cm7 » or « C–7 ». */
export type MinorNotation = 'm' | '–';

export interface AppSettings {
  minorNotation: MinorNotation;
}

export type { TempoMap };
