type Rec = Record<string, unknown>;
const FILE = readFileSync(path.resolve(__dirname, 'fixtures', 'published-main-v5.fab'));
const bytes = () => new Uint8Array(FILE);
const json = <T = Rec>(v: unknown) => JSON.parse(JSON.stringify(v)) as T;
const without = (o: Rec, ...keys: string[]): Rec => Object.fromEntries(Object.entries(o).filter(([k]) => !keys.includes(k)));

/** The document and the manifest exactly as the published app wrote them. */
async function rawEntries(): Promise<{ v5: Rec; manifest: Rec }> {
  const source = bytesSource(bytes());
  const entries = await readZipDirectory(source);
  const read = async (name: string) => JSON.parse(new TextDecoder().decode(await readEntryBytes(source, entries.find((e) => e.name === name)!))) as Rec;
  return { v5: await read(DOCUMENT_ENTRY), manifest: await read(MANIFEST_ENTRY) };
}

/** The original as the published app kept it: a 16-bit PCM WAV. */
function decodeWav(stored: StoredAudio): DecodedAudio {
  const v = new DataView(stored.bytes);
  expect(new TextDecoder().decode(new Uint8Array(stored.bytes, 0, 4))).toBe('RIFF');
  const n = v.getUint32(40, true) / 2;
  const ch = new Float32Array(n);
  for (let i = 0; i < n; i++) ch[i] = v.getInt16(44 + 2 * i, true) / 32768;
  return { channels: [ch], sampleRate: v.getUint32(24, true) };
}

describe('a .fab file written by the published app (document version 5)', () => {
  it('is what it claims: version 5, every part of a worked-on piece', async () => {
    const { v5, manifest } = await rawEntries();
    expect(v5.version).toBe(5);
    expect(manifest.documentVersion).toBe(5);
    expect((v5.analysis as Rec).version).toBe(1);
    const c = v5.corrections as Rec;
    expect((c.chords as unknown[]).length).toBe(3);
    expect((c.sections as Rec[]).map((x) => x.label)).toEqual(['A', 'Pont']);
    expect((c.tempoFixes as Rec[]).map((f) => f.kind)).toEqual(['continuity', 'fresh']);
    expect(((v5.separation as Rec).others as unknown[]).length).toBe(1);
    expect((v5.keptRender as Rec).tracks).toHaveLength(3);
    expect(Object.keys((v5.metronome as Rec).patterns as Rec)).toEqual(['7/8']);
    expect(((v5.markers as Rec).loops as Rec[]).map((l) => l.name)).toEqual(['Pont', 'Intro']);
    expect((v5.tracks as Rec[]).map((t) => [t.mute, t.solo, t.volume])).toEqual([
      [true, false, 1],
      [false, true, 0.55],
      [false, false, 1],
    ]);
  });

  it('the reader migrates it to version 6 field by field: everything of version 5 as it was, the new fields at their defaults', async () => {
    const { v5 } = await rawEntries();
    const opened = await openProjectFile(bytesSource(bytes()));
    await opened.verify();
    expect(opened.manifest.documentVersion).toBe(5);
    const v6 = json(opened.document);
    expect(v6.version).toBe(6);
    expect(Object.keys(v6).sort()).toEqual(Object.keys(v5).sort());
    for (const key of Object.keys(v5)) {
      if (key === 'version' || key === 'analysis' || key === 'corrections' || key === 'exportPrefs') continue;
      expect(v6[key], key).toEqual(v5[key]);
    }
    expect(v6.exportPrefs).toEqual({ ...defaultExportPreferences(), ...(v5.exportPrefs as Rec) });
    const c = v6.corrections as Rec;
    expect(without(c, 'keyChanges', 'structure')).toEqual(v5.corrections);
    expect(c.keyChanges).toBeNull();
    expect(c.structure).toEqual(emptyStructureCorrections());
    const a = v6.analysis as Rec;
    expect(a.version).toBe(2);
    expect(without(a, 'version', 'keyChanges', 'structure')).toEqual(without(v5.analysis as Rec, 'version'));
    expect(a.keyChanges).toEqual([]);
    expect(a.structure).toBeNull();
  });

  it('every track reads back with its number of frames and channels: both separations and the kept render', async () => {
    const { v5 } = await rawEntries();
    const opened = await openProjectFile(bytesSource(bytes()));
    const sep = v5.separation as { aside: Rec[]; others: { tracks: Rec[] }[] };
    const separated = [...(v5.tracks as Rec[]), ...sep.aside, ...sep.others.flatMap((o) => o.tracks)]
      .map((tr) => tr.audio as Rec)
      .filter((a) => a.origin === 'separated');
    expect(separated).toHaveLength(6);
    for (const a of separated) {
      const pcm = await opened.readTrack(a.id as string);
      expect([pcm.frames, pcm.channelCount, pcm.sampleRate], a.id as string).toEqual([a.frames, a.channels, a.sampleRate]);
    }
    for (const t of (v5.keptRender as { tracks: Rec[] }).tracks) {
      const pcm = await opened.readTrack(t.audioId as string);
      expect([pcm.frames, pcm.channelCount], t.audioId as string).toEqual([t.frames, t.channels]);
    }
    const original = sep.aside.find((tr) => (tr.audio as Rec).origin === 'original')!.audio as Rec;
    const stored = await opened.readOriginal(original.id as string);
    expect(stored.mimeType).toBe('audio/wav');
    expect(decodeWav(stored).channels[0]!.length).toBe(original.frames);
  });

  describe('opened in the app', () => {
    let storage: MemoryStorage;
    beforeEach(() => {
      appStore.setState(initialState(), true);
      appStore.setState((s) => ({ ui: { ...s.ui, newPieceOpen: false } }));
      clearAudio();
      const engine = new MockEngine(fakeClock().clock);
      replaceEngine(engine);
      connectEngine(appStore, engine);
      storage = new MemoryStorage();
      replaceProjectStorage(storage);
      getKeeper().start();
      startRenderWatch();
      startKeptRenderWatch();
      setDevice({ phone: false, gpu: 'apple', browser: 'chromium', memoryGB: 8, cores: 8, desktopApp: true });
    });

    it('the piece is as the file says, kept on the device, its render heard, the other separation one click away', async () => {
      const { v5 } = await rawEntries();
      const migrated = (await openProjectFile(bytesSource(bytes()))).document;
      await openProjectSource(bytesSource(bytes()), 'Petit blues publié.fab', {}, { decode: async (stored) => decodeWav(stored) });
      await new Promise((r) => setTimeout(r, 20));
      const s = appStore.getState();
      expect({ ...toProjectDocument(s)!, savedAt: '' }).toEqual({ ...migrated, savedAt: '' });
      for (const tr of s.tracks) expect(getAudio(tr.audio.id)?.frames).toBe(tr.audio.frames);
      // The other separation, on the device.
      for (const tr of s.separation.others[0]!.tracks) expect((await storage.loadTrackAudio(tr.audio.id))?.frames).toBe(tr.audio.frames);
      // The kept render: same key and tempo, heard at once, on the device too.
      expect(selectApplyState(s)).toBe('applied');
      for (const t of (v5.keptRender as { tracks: { trackId: string; audioId: string; frames: number }[] }).tracks) {
        expect(keptRenderAudio()!.get(t.trackId)!.frames).toBe(t.frames);
        expect((await storage.loadTrackAudio(t.audioId))?.frames).toBe(t.frames);
      }
      await getKeeper().settled();
      expect((await storage.loadCurrent())?.version).toBe(6);
      expect(await chooseSeparation(s.separation.others[0]!.result.id)).toBe(true);
      expect(appStore.getState().separation.result?.modelId).toBe('htdemucs-6s');
    });
  });
});
