// A `.fab` file written by the published app opens in 1.0.0 with nothing lost.
//
// `fixtures/published-main-v5.fab` was written once by the code of branch main
// at commit 09da8d8 (16 November 2026, document version 5, file layout 2): a
// throwaway vitest run in a worktree of that commit drove its store (import of
// a 0.15 s mono WAV kept on the device, the mock analysis, two separations
// with two tools, a mix, hand chords and a rewritten span, two sections, two
// tempo fixes, a key and a tuning, two named loops, the metronome in 7/8 with
// its accents and the acceleration, then « Appliquer » at -2 semitones +12
// cents and 0.9× tempo, kept), then its `buildProjectFile` with the Node FLAC
// encoder. Nothing of this file is generated by the code under test.

