import path from 'node:path';
import { beforeEach, describe, expect, it } from 'vitest';
import { replaceEngine } from '../audio';
import { connectEngine } from '../audio/connect';
import { MockEngine } from '../audio/MockEngine';
import { clearAudio, getAudio, type DecodedAudio } from '../audio/registry';
import { defaultExportPreferences } from '../model/audioExport';
import { emptyStructureCorrections } from '../model/structure';
import { keptRenderAudio, selectApplyState, startKeptRenderWatch, startRenderWatch } from '../render/controller';
import { setDevice } from '../separation/device';
import { chooseSeparation } from '../separation/runner';
